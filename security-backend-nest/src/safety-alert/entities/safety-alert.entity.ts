import {
  Column,
  CreateDateColumn,
  Entity,
  Index,
  ManyToOne,
  PrimaryGeneratedColumn,
  UpdateDateColumn,
} from 'typeorm';
import { Company } from '../../company/entities/company.entity';
import { GuardProfile } from '../../guard-profile/entities/guard-profile.entity';
import { Shift } from '../../shift/entities/shift.entity';

export enum SafetyAlertType {
  CHECK_CALL = 'check_call',
  PANIC = 'panic',
  /**
   * A Guard-raised request about the site. Historical rows carry this type and remain valid; it is
   * presented as SITE REQUEST. New records will use SITE_REQUEST once the Guard app is renamed.
   */
  WELFARE = 'welfare',
  SITE_REQUEST = 'site_request',
  LATE_CHECKIN = 'late_checkin',
  /**
   * A missed Welfare Check. Two distinct roles, told apart by `welfareWindowIndex`:
   *   NOT NULL — durable per-window evidence, one row per missed window
   *   NULL     — the actionable shift-level summary, and every legacy rolling alert
   */
  MISSED_CHECKCALL = 'missed_checkcall',
  MISSING_BOOK_OFF = 'missing_book_off',
  OTHER = 'other',
  /**
   * Migration 63. A Guard's mandatory company SIA or Right to Work check expired, was recorded as not
   * confirmed, or is missing while they are on an in-progress shift. Raised by the backend sweep; never
   * a panic/SOS alert, and never closes or changes the shift. See SafetyAlertService.runComplianceLapseScan.
   */
  COMPLIANCE_LAPSE = 'compliance_lapse',
  /**
   * Migration 69 (Patrols P1-B). Raised only by the patrol sweep, one per actionable patrol exception (patrolExceptionId),
   * never by a client. Separate from Welfare: no Welfare window, reminder, counter or report reads them.
   *   PATROL_MISSED       nothing was started for a due window by its start deadline
   *   PATROL_ABANDONED    started, not completed by the completion deadline
   *   PATROL_INCOMPLETE   completed with a reason, or without required photos (policy decides whether a reason needs action)
   *   CHECKPOINT_MISSED   completed without every required checkpoint of its route
   *   PATROL_UNVERIFIED   required evidence still not on the server at the sync deadline (only when the policy escalates it)
   */
  PATROL_MISSED = 'patrol_missed',
  PATROL_ABANDONED = 'patrol_abandoned',
  PATROL_INCOMPLETE = 'patrol_incomplete',
  CHECKPOINT_MISSED = 'checkpoint_missed',
  PATROL_UNVERIFIED = 'patrol_unverified',
}

/** The patrol alert types (Migration 69). */
export const PATROL_ALERT_TYPES: readonly SafetyAlertType[] = [
  SafetyAlertType.PATROL_MISSED,
  SafetyAlertType.PATROL_ABANDONED,
  SafetyAlertType.PATROL_INCOMPLETE,
  SafetyAlertType.CHECKPOINT_MISSED,
  SafetyAlertType.PATROL_UNVERIFIED,
];

export function isPatrolAlertType(type: SafetyAlertType | string | null | undefined): boolean {
  return PATROL_ALERT_TYPES.includes(type as SafetyAlertType);
}

/**
 * The ONLY alert types a Guard may raise through the API (POST /alerts):
 *   PANIC         the Emergency / SOS action
 *   SITE_REQUEST  a Guard-raised request about the site
 *   WELFARE       the historical stored label for a Site Request (older app builds)
 *   OTHER         the default when no type is sent: a manual safety report
 *
 * Every other type is SYSTEM-GENERATED by trusted server-side sweeps and must never be accepted from a
 * client: MISSED_CHECKCALL and the legacy CHECK_CALL (welfare sweep), MISSING_BOOK_OFF (welfare sweep),
 * LATE_CHECKIN (legacy, no live writer), COMPLIANCE_LAPSE (compliance lapse sweep) and the patrol types (patrol
 * sweep). A forged one would
 * read as a genuine system finding in the control room's queue and in reports.
 */
export const GUARD_RAISABLE_ALERT_TYPES: readonly SafetyAlertType[] = [
  SafetyAlertType.PANIC,
  SafetyAlertType.SITE_REQUEST,
  SafetyAlertType.WELFARE,
  SafetyAlertType.OTHER,
];

/** The mandatory company check a compliance lapse alert is about. */
export type ComplianceLapseCategory = 'sia' | 'right_to_work';
/** Why it lapsed, from the company assessment's requirement state. */
export type ComplianceLapseReason = 'expired' | 'not_confirmed' | 'missing';

export enum SafetyAlertPriority {
  LOW = 'low',
  MEDIUM = 'medium',
  HIGH = 'high',
  CRITICAL = 'critical',
}

export enum SafetyAlertStatus {
  OPEN = 'open',
  ACKNOWLEDGED = 'acknowledged',
  CLOSED = 'closed',
}

/**
 * Both indexes are declared here as well as in migration 59 so the entity metadata tells the truth
 * about the constraints the welfare sweep relies on. They are what make its ON CONFLICT DO NOTHING
 * inserts idempotent, so anything that builds this schema from entity metadata needs them too.
 */
@Index('uq_safety_alerts_shift_welfare_window', ['shift', 'welfareWindowIndex'], {
  unique: true,
  where: '"welfareWindowIndex" IS NOT NULL',
})
@Index('uq_safety_alerts_shift_missing_book_off', ['shift'], {
  unique: true,
  where: `"type" = 'missing_book_off'`,
})
/**
 * Migration 63. At most one ACTIVE (open or acknowledged) compliance lapse alert per company, shift and
 * check category, however many sweeps run and on however many instances.
 */
@Index('uq_safety_alerts_compliance_lapse_active', ['company', 'shift', 'complianceCategory'], {
  unique: true,
  where: `"type" = 'compliance_lapse' AND "status" IN ('open', 'acknowledged')`,
})
/**
 * Migration 63. The same lapse (same check, same reason) is raised once per shift, ever: closing it is a
 * decision, and the sweep must not re-raise it five minutes later. A different lapse (a new check that
 * then lapses, or a change of reason) is a new event and may be raised once the previous one is closed.
 */
@Index('uq_safety_alerts_compliance_lapse_key', ['shift', 'complianceCategory', 'lapseKey'], {
  unique: true,
  where: `"type" = 'compliance_lapse'`,
})
/**
 * Migration 69. One alert per patrol exception, however many sweeps run and on however many instances: the patrol sweep
 * inserts with ON CONFLICT DO NOTHING against this index.
 */
@Index('uq_safety_alerts_patrol_exception', ['patrolExceptionId'], {
  unique: true,
  where: '"patrolExceptionId" IS NOT NULL',
})
/** Migration 71. One reconciliation alert per (reconciliation run, key): summaries per site, and the horizon alert. */
@Index('uq_safety_alerts_patrol_reconciliation', ['patrolReconciliationRunId', 'patrolWindowKey'], {
  unique: true,
  where: '"patrolReconciliationRunId" IS NOT NULL',
})
@Entity('safety_alerts')
export class SafetyAlert {
  @PrimaryGeneratedColumn()
  id!: number;

  @ManyToOne(() => Company, { eager: true, onDelete: 'CASCADE' })
  company!: Company;

  @ManyToOne(() => GuardProfile, { eager: true, onDelete: 'CASCADE' })
  guard!: GuardProfile;

  @ManyToOne(() => Shift, { eager: true, nullable: true, onDelete: 'SET NULL' })
  shift?: Shift | null;

  @Column({
    type: 'enum',
    enum: SafetyAlertType,
    default: SafetyAlertType.OTHER,
  })
  type!: SafetyAlertType;

  @Column({
    type: 'enum',
    enum: SafetyAlertPriority,
    default: SafetyAlertPriority.MEDIUM,
  })
  priority!: SafetyAlertPriority;

  @Column({ type: 'text' })
  message!: string;

  /**
   * Which Welfare Check window this row is evidence for, counted from the scheduled shift start.
   *
   * NULL on everything else, including the shift-level summary alert and every alert written by the
   * old rolling sweep. A partial unique index on (shiftId, welfareWindowIndex) WHERE NOT NULL is what
   * makes the sweep idempotent and safe against concurrent runs.
   */
  @Column({ type: 'int', nullable: true })
  welfareWindowIndex?: number | null;

  @Column({
    type: 'enum',
    enum: SafetyAlertStatus,
    default: SafetyAlertStatus.OPEN,
  })
  status!: SafetyAlertStatus;

  @Column({ type: 'timestamp', nullable: true })
  acknowledgedAt?: Date | null;

  @Column({ type: 'int', nullable: true })
  acknowledgedByUserId?: number | null;

  @Column({ type: 'timestamp', nullable: true })
  closedAt?: Date | null;

  @Column({ type: 'int', nullable: true })
  closedByUserId?: number | null;

  /**
   * Why Control closed this, as a stable machine value from the set for THIS alert type — never the
   * words that were on the button. NULL on a row closed before resolution evidence was captured, and
   * on one the system closed itself (a late Book Off answering its own Missing Book Off alert).
   */
  @Column({ type: 'varchar', length: 64, nullable: true })
  resolutionReason?: string | null;

  /** What Control wrote. Separate from `message`, which is the alert as it was raised. */
  @Column({ type: 'text', nullable: true })
  resolutionNote?: string | null;

  /** Migration 63, compliance_lapse only: 'sia' | 'right_to_work'. NULL on every other alert. */
  @Column({ type: 'varchar', length: 32, nullable: true })
  complianceCategory?: ComplianceLapseCategory | null;

  /** Migration 63, compliance_lapse only: 'expired' | 'not_confirmed' | 'missing'. */
  @Column({ type: 'varchar', length: 32, nullable: true })
  complianceReason?: ComplianceLapseReason | null;

  /**
   * Migration 63, compliance_lapse only: category, the lapsed check's id (or 'none') and the reason.
   * Internal deduplication key; contains no evidence.
   */
  @Column({ type: 'varchar', length: 120, nullable: true })
  lapseKey?: string | null;

  /**
   * Migration 69, patrol alerts only: the patrol exception this alert carries (patrol_exceptions.safetyAlertId points
   * back), the run it concerns (null for a missed window, which has no run) and the window. The company web links a
   * patrol alert to /patrols/runs/{patrolRunId}, or to the exception when there is no run. NULL on every other alert.
   *
   * The patrol columns are select: false: every existing alert read (Live Operations, reports, the Guard's own list) stays
   * byte-identical to before Migration 69, and the columns are attached only to patrol alerts, by
   * SafetyAlertService.attachPatrolLinks.
   */
  @Column({ type: 'int', nullable: true, select: false })
  patrolExceptionId?: number | null;

  @Column({ type: 'int', nullable: true, select: false })
  patrolRunId?: number | null;

  @Column({ type: 'varchar', length: 64, nullable: true, select: false })
  patrolWindowKey?: string | null;

  /**
   * Migration 69: patrol evidence for this alert's window / run reached the server after the alert was raised. The alert is
   * NOT closed by it: it is downgraded (priority low) and offers the resolution "patrol_completed_late_sync" for a person
   * to confirm. The message stays as raised; the annotation says what arrived.
   */
  @Column({ type: 'timestamptz', nullable: true, select: false })
  patrolLateSyncAt?: Date | null;

  @Column({ type: 'varchar', length: 500, nullable: true, select: false })
  patrolAnnotation?: string | null;

  /**
   * Migration 71 (#67): a patrol reconciliation alert — the summary of the windows found missed after a sweep outage (one
   * per site and reconciliation run, patrolWindowKey 'reconciliation:site:{siteId}') or the one alert for windows beyond
   * the reconciliation horizon that were NOT judged (patrolWindowKey 'reconciliation:horizon'). It carries no exception.
   */
  @Column({ type: 'int', nullable: true, select: false })
  patrolReconciliationRunId?: number | null;

  @CreateDateColumn()
  createdAt!: Date;

  @UpdateDateColumn()
  updatedAt!: Date;
}
