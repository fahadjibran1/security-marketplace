import { SetMetadata } from '@nestjs/common';
import { CompanyVerificationStatus } from './company-verification';

/**
 * SEC-PUBLIC-03: what a company may DO in each verification state.
 *
 * Every route that changes data and that a company user (company / company_admin / company_staff) can reach is tagged
 * with exactly one capability (@CompanyCapability). CompanyApprovalInterceptor (registered globally) refuses the request
 * with 403 COMPANY_NOT_APPROVED when the caller's company's state does not grant that capability. A mutating route with
 * NO tag is treated as NEW_OPERATIONS (approved only), so a route added later is closed until someone classifies it;
 * company-capability-policy.spec.ts also fails the build until it is classified, and keeps
 * docs/security/COMPANY-CAPABILITY-MATRIX.md (generated by scripts/company-capability-matrix.ts) in step with the code.
 *
 * Reads (GET / HEAD / OPTIONS) are never refused by this policy: every state keeps access to its own records (tenant
 * isolation and role permissions are enforced, unchanged, by the routes themselves).
 */
export enum CompanyCapability {
  /** Sign-in, sign-out, password recovery, account deletion, marking notifications read. */
  ACCOUNT = 'account',
  /** Correcting the registration details S4 verifies (PATCH /companies/me). */
  REGISTRATION = 'registration',
  /** A rejected company asking S4 to look again, after correcting its details. */
  RECONSIDERATION = 'reconsideration',
  /** Acting on Guard safety: alerts, incidents, patrol exceptions. Never withheld. */
  SAFETY = 'safety',
  /**
   * Internal set-up that commits no Guard and contacts nobody outside the company: clients, sites, pricing, pay rules,
   * patrol configuration, internal policies and authorisations.
   */
  SETUP = 'setup',
  /**
   * Starting new operational activity: publishing jobs, hiring, inviting or linking Guards, creating or re-staffing
   * shifts and rota positions, giving outside people access (client portal, staff invitations).
   */
  NEW_OPERATIONS = 'new_operations',
  /**
   * Completing, recording and winding down work already in place: attendance and its corrections, timesheets, client
   * approvals, invoicing and payroll for time worked, amendments to existing shifts, cancellations, compliance and
   * personnel records of the existing workforce, evidence retention.
   */
  EXISTING_OBLIGATIONS = 'existing_obligations',
}

const S = CompanyVerificationStatus;
const C = CompanyCapability;

/** The policy. Approved companies keep everything; nothing else is ever granted NEW_OPERATIONS. */
export const COMPANY_CAPABILITY_MATRIX: Readonly<Record<CompanyVerificationStatus, readonly CompanyCapability[]>> = {
  [S.APPROVED]: [C.ACCOUNT, C.REGISTRATION, C.SAFETY, C.SETUP, C.NEW_OPERATIONS, C.EXISTING_OBLIGATIONS],
  // Getting ready while S4 verifies: account, details, internal set-up. No Guard, client or outsider is involved yet.
  [S.PENDING_VERIFICATION]: [C.ACCOUNT, C.REGISTRATION, C.SAFETY, C.SETUP],
  // Correct the registration and ask again; nothing operational.
  [S.REJECTED]: [C.ACCOUNT, C.REGISTRATION, C.RECONSIDERATION, C.SAFETY],
  // No new activity; safety and the completion of what is already in place continue, so Guards are paid and safe.
  [S.SUSPENDED]: [C.ACCOUNT, C.SAFETY, C.EXISTING_OBLIGATIONS],
};

export function companyMay(status: CompanyVerificationStatus, capability: CompanyCapability): boolean {
  return COMPANY_CAPABILITY_MATRIX[status]?.includes(capability) ?? false;
}

export const COMPANY_CAPABILITY_KEY = 's4:company-capability';
/** Classifies a mutating route reachable by company users (see CompanyCapability). */
export const CompanyCapabilityRequired = (capability: CompanyCapability) => SetMetadata(COMPANY_CAPABILITY_KEY, capability);
