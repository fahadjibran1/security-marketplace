import { HttpStatus, Injectable } from '@nestjs/common';
import { DataSource } from 'typeorm';
import { JwtPayload } from '../auth/types/jwt-payload.type';
import { CompanyPermission } from '../company-membership/company-membership-types';
import { PatrolWindowsDayQueryDto } from './dto/patrol.dto';
import { PatrolAccessService } from './patrol-access.service';
import { PatrolErrorCode, patrolError } from './patrol-constants';
import { usableZone } from './patrol-query.service';
import { PatrolWindow, PatrolWindowService, localDateOf, siteDayBounds } from './patrol-window.service';

export type PatrolWindowsDaySite = {
  siteId: number;
  timeZone: string;
  /** The site-local date counted. */
  date: string;
  /** The instants bounding that day at the site (23 or 25 hours on a DST day). */
  dayStart: string;
  dayEnd: string;
  windowsDue: number;
  windowsCompleted: number;
  windowsOutstanding: number;
};

/**
 * "Patrol windows due today" (#78) — computed, never stored, never estimated.
 *
 *   due          every window of every ACTIVE, non-archived schedule whose START falls in the site-local day
 *                [midnight, next midnight) — generated by the P1-B window engine (PatrolWindowService.windowsBetween,
 *                site-local wall-clock slots; on a DST night a slot inside the spring gap does not exist and the repeated
 *                autumn hour is not a second slot). An overnight period's slots after midnight are due on the day they
 *                start. Due regardless of who is on duty: it is the schedule's demand for the day, not a judgement.
 *   completed    of those, the windows with at least one run recorded against the window (its schedule and windowKey)
 *                whose status is `completed`. Counted per WINDOW: with a per-guard requirement one completed run marks
 *                the window completed here, while missed scopes are still raised as exceptions by the sweep.
 *   outstanding  due − completed: still to do, in progress, incomplete, or missed.
 *
 * Tenant- and site-scoped: the company comes only from the session (PatrolAccessService, patrols.view, 404 while
 * Patrols is off); a siteId that is not the company's is 404 PATROL_SITE_NOT_FOUND. Each site is counted on its OWN
 * zone, so `date` names each site's local day.
 */
@Injectable()
export class PatrolWindowsDayService {
  constructor(
    private readonly dataSource: DataSource,
    private readonly access: PatrolAccessService,
    private readonly windows: PatrolWindowService,
  ) {}

  async day(user: JwtPayload, query: PatrolWindowsDayQueryDto, now: Date = new Date()) {
    const actor = await this.access.companyActor(user, CompanyPermission.PATROLS_VIEW);
    const siteId = query.siteId ?? null;
    const siteRows = await this.dataSource.query(
      `SELECT "id", "timezone" FROM "sites" WHERE "companyId" = $1 AND ($2::int IS NULL OR "id" = $2) ORDER BY "id"`,
      [actor.companyId, siteId],
    );
    if (siteId != null && !siteRows.length) {
      throw patrolError(HttpStatus.NOT_FOUND, PatrolErrorCode.SITE_NOT_FOUND, 'Site not found.');
    }
    const schedules = await this.dataSource.query(
      `SELECT * FROM "patrol_schedules" WHERE "companyId" = $1 AND ($2::int IS NULL OR "siteId" = $2) AND "active" AND "archivedAt" IS NULL ORDER BY "id"`,
      [actor.companyId, siteId],
    );

    // Each site's day and its due windows, from the engine.
    const sites: PatrolWindowsDaySite[] = [];
    const due: Array<{ siteId: number; window: PatrolWindow }> = [];
    for (const row of siteRows) {
      const id = Number(row.id);
      const own = schedules.filter((s: any) => Number(s.siteId) === id);
      if (!own.length && id !== siteId) continue; // a site with no schedule has nothing due (listed only when asked for)
      const timeZone = usableZone(row.timezone);
      const date = query.date ?? localDateOf(now, timeZone);
      const { start, end } = siteDayBounds(date, timeZone);
      const cache = new Map<string, number>();
      let count = 0;
      for (const schedule of own) {
        for (const window of this.windows.windowsBetween(schedule, timeZone, start, end, cache)) {
          if (window.start.getTime() < start.getTime() || window.start.getTime() >= end.getTime()) continue;
          due.push({ siteId: id, window });
          count += 1;
        }
      }
      sites.push({ siteId: id, timeZone, date, dayStart: start.toISOString(), dayEnd: end.toISOString(), windowsDue: count, windowsCompleted: 0, windowsOutstanding: count });
    }

    // Which of them have a completed run (company-scoped; keys are distinct per schedule).
    const completedKeys = new Set<string>();
    if (due.length) {
      const rows = await this.dataSource.query(
        `SELECT DISTINCT "scheduleId", "windowKey" FROM "patrol_runs"
          WHERE "companyId" = $1 AND "status" = 'completed' AND "scheduleId" = ANY($2::int[]) AND "windowKey" = ANY($3::text[])`,
        [actor.companyId, [...new Set(due.map((d) => d.window.scheduleId))], due.map((d) => d.window.windowKey)],
      );
      for (const r of rows) completedKeys.add(`${Number(r.scheduleId)}|${r.windowKey}`);
    }
    for (const { siteId: id, window } of due) {
      if (!completedKeys.has(`${window.scheduleId}|${window.windowKey}`)) continue;
      const site = sites.find((s) => s.siteId === id)!;
      site.windowsCompleted += 1;
      site.windowsOutstanding -= 1;
    }

    const dates = [...new Set(sites.map((s) => s.date))];
    const sum = (k: 'windowsDue' | 'windowsCompleted' | 'windowsOutstanding') => sites.reduce((n, s) => n + s[k], 0);
    return {
      /** The site-local date counted: the one asked for, or today when every site counted shares it (null otherwise). */
      date: query.date ?? (dates.length === 1 ? dates[0] : siteId != null ? sites[0]?.date ?? null : null),
      dateBasis: 'site_local' as const,
      siteId,
      generatedAt: now.toISOString(),
      windowsDue: sum('windowsDue'),
      windowsCompleted: sum('windowsCompleted'),
      windowsOutstanding: sum('windowsOutstanding'),
      completionBasis: 'window_with_a_completed_run' as const,
      sites,
    };
  }
}
