import pg from '../node_modules/pg/lib/index.js';
const { Client } = pg;
import { readFileSync } from 'fs';
const migFile = readFileSync(new URL('../scripts/check-staging-migrations.mjs', import.meta.url), 'utf8');
const url = migFile.match(/const STAGING_DB = '([^']+)'/)[1];
const c = new Client({ connectionString: url, ssl: { rejectUnauthorized: false } });
await c.connect();
const r = await c.query("SELECT column_name, is_nullable, column_default FROM information_schema.columns WHERE table_name='guard_profiles' AND table_schema='public' ORDER BY ordinal_position");
for (const row of r.rows) console.log(`${row.column_name}: nullable=${row.is_nullable} default=${row.column_default}`);
await c.end();
