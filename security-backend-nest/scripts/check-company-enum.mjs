import pg from '../node_modules/pg/lib/index.js';
const { Client } = pg;
import { readFileSync } from 'fs';
const migFile = readFileSync(new URL('../scripts/check-staging-migrations.mjs', import.meta.url), 'utf8');
const url = migFile.match(/const STAGING_DB = '([^']+)'/)[1];
const c = new Client({ connectionString: url, ssl: { rejectUnauthorized: false } });
await c.connect();
const r = await c.query("SELECT unnest(enum_range(NULL::companies_status_enum))::text as val");
console.log('company status:', r.rows.map(x => x.val).join(', '));
const r2 = await c.query("SELECT column_name, is_nullable FROM information_schema.columns WHERE table_name='companies' ORDER BY ordinal_position");
console.log('companies cols:', r2.rows.map(x => `${x.column_name}(${x.is_nullable})`).join(', '));
await c.end();
