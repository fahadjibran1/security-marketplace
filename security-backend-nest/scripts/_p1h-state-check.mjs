import pg from '../node_modules/pg/lib/index.js';
const { Client } = pg;
const db = new Client({ connectionString: process.env.DATABASE_URL, ssl: { rejectUnauthorized: false } });
await db.connect();
const m = await db.query('SELECT timestamp, name FROM typeorm_migrations WHERE timestamp IN (1720800000000,1720800000001,1720800000002) ORDER BY timestamp');
console.log('P1H_MIGRATIONS:', JSON.stringify(m.rows));
const cpu = await db.query('SELECT id, email, role, "clientId" FROM client_portal_users ORDER BY id');
console.log('CLIENT_PORTAL_USERS:', JSON.stringify(cpu.rows));
const cl = await db.query('SELECT id, name, "companyId" FROM clients ORDER BY id');
console.log('CLIENTS:', JSON.stringify(cl.rows));
const si = await db.query('SELECT id, name, "clientId", timezone FROM sites ORDER BY id');
console.log('SITES:', JSON.stringify(si.rows));
const ts = await db.query(`SELECT id, "approvalStatus", "billingStatus", "companyId", "shiftId" FROM timesheets WHERE "approvalStatus"='approved' ORDER BY id DESC LIMIT 10`);
console.log('APPROVED_TS:', JSON.stringify(ts.rows));
const req = await db.query('SELECT id, status, "weekCommencing", "companyId", "clientId", "siteId" FROM client_weekly_approval_requests ORDER BY id');
console.log('APPROVAL_REQUESTS:', JSON.stringify(req.rows));
const users = await db.query(`SELECT id, email, role FROM users WHERE email LIKE 'p1h-%' ORDER BY id`);
console.log('P1H_USERS:', JSON.stringify(users.rows));
const sh = await db.query(`SELECT id, "siteId", "companyId", "guardId", start FROM shifts WHERE "siteId" IS NOT NULL ORDER BY id DESC LIMIT 10`);
console.log('SHIFTS:', JSON.stringify(sh.rows));
await db.end();
