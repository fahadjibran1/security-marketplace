/**
 * Generates docs/security/COMPANY-CAPABILITY-MATRIX.md from the code (SEC-PUBLIC-03): the policy matrix and every mutating
 * route a company user can reach, with its capability. company-capability-policy.spec.ts fails if the committed document
 * differs from what this produces, so the document is always the policy that actually runs.
 *
 *   npx ts-node -r tsconfig-paths/register scripts/company-capability-matrix.ts           write the document
 *   npx ts-node -r tsconfig-paths/register scripts/company-capability-matrix.ts --list    print the routes only
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadRoutes, isMutating, companyReachable, RouteEntry } from './support/route-inventory';
import { COMPANY_CAPABILITY_MATRIX, CompanyCapability } from '../src/company/company-capability';
import { CompanyVerificationStatus } from '../src/company/company-verification';

export const MATRIX_DOC = join(__dirname, '..', '..', 'docs', 'security', 'COMPANY-CAPABILITY-MATRIX.md');

export function companyWriteRoutes(): RouteEntry[] {
  return loadRoutes().filter((r) => isMutating(r) && companyReachable(r));
}

const STATES = [
  CompanyVerificationStatus.APPROVED,
  CompanyVerificationStatus.PENDING_VERIFICATION,
  CompanyVerificationStatus.REJECTED,
  CompanyVerificationStatus.SUSPENDED,
];

export function renderMatrix(): string {
  const routes = companyWriteRoutes();
  const capabilities = Object.values(CompanyCapability);
  const tick = (s: CompanyVerificationStatus, c: CompanyCapability) => (COMPANY_CAPABILITY_MATRIX[s].includes(c) ? 'yes' : '—');
  const lines: string[] = [
    '# Company capability matrix (SEC-PUBLIC-03)',
    '',
    '<!-- Generated by security-backend-nest/scripts/company-capability-matrix.ts. Do not edit by hand:',
    '     company-capability-policy.spec.ts fails the release gate if this file differs from the code. -->',
    '',
    'What a company may change in each verification state. Reads are never refused by this policy: every state keeps',
    'access to its own records, and role permissions and tenant isolation apply unchanged. A mutating route with no',
    'classification is treated as `new_operations` (approved only) and fails the release gate until it is classified.',
    'Platform administrators, Guards and client-portal users are not subject to this policy; Guards are separately',
    'refused jobs, applications and invitations of any company that is not approved.',
    '',
    '## Policy',
    '',
    `| Capability | ${STATES.join(' | ')} |`,
    `|---|${STATES.map(() => '---').join('|')}|`,
    ...capabilities.map((c) => `| \`${c}\` | ${STATES.map((s) => tick(s, c)).join(' | ')} |`),
    '',
    'A refusal is `403` with `code: "COMPANY_NOT_APPROVED"`, the company\'s `verificationStatus` and the refused `capability`.',
    'When a user can act for more than one company (a membership and an owned company), the most restrictive state applies.',
    'An approved company is never refused by this policy; asking for reconsideration while approved is refused by the route',
    'itself (409), since only a rejected company can ask.',
    '',
    '## Routes',
    '',
    `${routes.length} mutating routes are reachable by company users.`,
    '',
  ];
  for (const c of capabilities) {
    const rows = routes.filter((r) => r.capability === c);
    if (!rows.length) continue;
    lines.push(`### \`${c}\` — ${STATES.filter((s) => COMPANY_CAPABILITY_MATRIX[s].includes(c)).join(', ')}`, '');
    lines.push('| Method | Path | Handler |', '|---|---|---|');
    for (const r of rows) lines.push(`| ${r.method} | \`${r.path}\` | ${r.handler} |`);
    lines.push('');
  }
  const unclassified = routes.filter((r) => !r.capability);
  if (unclassified.length) {
    lines.push('### UNCLASSIFIED (treated as `new_operations`)', '', '| Method | Path | Handler |', '|---|---|---|');
    for (const r of unclassified) lines.push(`| ${r.method} | \`${r.path}\` | ${r.handler} |`);
    lines.push('');
  }
  return lines.join('\n');
}

if (require.main === module) {
  if (process.argv.includes('--list')) {
    for (const r of companyWriteRoutes()) {
      console.log(`${r.method.padEnd(6)} ${r.path.padEnd(60)} ${r.handler.padEnd(56)} ${(r.roles ?? ['*']).join(',').padEnd(40)} ${r.capability ?? '-'}`);
    }
  } else {
    writeFileSync(MATRIX_DOC, renderMatrix());
    console.log(`wrote ${MATRIX_DOC}`);
  }
}
